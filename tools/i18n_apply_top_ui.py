def apply(data: dict, lang: str, mapping: dict[str, str]) -> int:
    d = data.get(lang)
    if not isinstance(d, dict):
        return 0
    changed = 0
    for k in TOP_KEYS:
        if k in mapping and mapping[k]:
            if d.get(k) != mapping[k]:
                d[k] = mapping[k]
                changed += 1
    return changed


